/**
 * App theme. Always uses the app's brand palette (derived from seed #00875A) in both
 * light and dark mode — Material You dynamic color is intentionally not used, so the
 * app looks the same on every device instead of re-theming from the user's wallpaper.
 */
@Composable
fun PersonalMoneyManagemntTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val financeColors = if (darkTheme) DarkFinanceColors else LightFinanceColors

    CompositionLocalProvider(LocalFinanceColors provides financeColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            shapes = AppShapes,
            content = content
        )
    }
}
